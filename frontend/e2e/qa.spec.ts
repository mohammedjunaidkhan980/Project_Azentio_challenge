import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('demo enquiry can be completed using keyboard controls', async ({ page }) => {
  await page.goto('/demo')
  await page.getByLabel('Your name').focus()
  await page.keyboard.type('Keyboard Example')
  await page.keyboard.press('Tab')
  await expect(page.getByLabel('Email address')).toBeFocused()
  await page.keyboard.type('keyboard@example.com')
  await page.keyboard.press('Tab')
  await expect(page.getByLabel('Organisation', { exact: true })).toBeFocused()
  await page.keyboard.type('Fictional QA Bank')
  await page.keyboard.press('Tab')
  await expect(page.getByLabel('What would you like to explore?')).toBeFocused()
  await page.keyboard.type('Synthetic keyboard journey')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('checkbox', { name: /I understand/ })).toBeFocused()
  await page.keyboard.press('Space')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Record demo enquiry' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'Preview enquiry recorded.' })).toBeVisible()
})

test('radio choices are keyboard accessible and save never silently proposes publication', async ({ page }) => {
  await page.goto('/observations/new')
  await page.getByLabel('Title', { exact: true }).fill('Organisation-only synthetic note')
  await page.getByLabel('What did you observe?').fill('Synthetic organisation-only context, not a community publication.')
  await page.getByRole('radio', { name: /Only me/ }).focus()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('radio', { name: /My organisation/ })).toBeChecked()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('radio', { name: /Propose community sharing/ })).toBeChecked()
  await page.getByRole('checkbox', { name: /I allow this synthetic/ }).check()
  await page.getByRole('checkbox', { name: /I explicitly permit/ }).check()
  await page.getByRole('button', { name: 'Save draft' }).click()
  await expect(page.getByText('Private draft', { exact: true })).toBeVisible()
  await expect(page.getByRole('status')).toContainText('No shared copy was created')
  await page.getByRole('link', { name: 'Moderator review', exact: true }).click()
  await page.getByRole('combobox', { name: /Preview persona/ }).selectOption('moderator')
  await expect(page.getByText('Organisation-only synthetic note', { exact: true })).toHaveCount(0)
})

