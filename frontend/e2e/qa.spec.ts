for (const route of ['/missing-page', '/offerings/missing', '/review', '/observations/unknown']) {
  test(`fallback ${route} has a primary heading and accessible recovery`, async ({ page }) => {
    await page.goto(route)
    await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
    expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()).violations).toEqual([])
    expect(await page.getByRole('link', { name: /Back to/ }).count()).toBeGreaterThan(0)
  })
}

test('P0 navigation produces no runtime errors or outbound service requests', async ({ page }) => {
  const runtimeErrors: string[] = []
  const externalRequests: string[] = []
  page.on('pageerror', error => runtimeErrors.push(error.message))
  page.on('request', request => { if (!request.url().startsWith('http://127.0.0.1:') && !request.url().startsWith('data:')) externalRequests.push(request.url()) })
  await page.goto('/')
  await page.getByRole('link', { name: 'Explore AI offerings', exact: true }).click()
  await page.getByRole('link', { name: /Explore offering\s*: Financial/ }).click()
  await page.getByRole('link', { name: 'Request a demo', exact: true }).click()
  await page.getByRole('link', { name: 'Client workspace', exact: true }).click()
  await page.getByRole('link', { name: 'New observation' }).click()
  await page.getByRole('link', { name: 'Approved learning', exact: true }).click()
  await page.getByRole('link', { name: 'Moderator review', exact: true }).click()
  expect(runtimeErrors).toEqual([])
  expect(externalRequests).toEqual([])
})

test('mobile moderation dialog traps keyboard focus and keeps all actions reachable', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 800 })
  await page.goto('/review')
  await page.getByRole('combobox', { name: /Preview persona/ }).selectOption('moderator')
  await page.getByRole('link', { name: /Add context to seasonal/ }).click()
  await page.getByRole('button', { name: 'Use synthetic safe-copy example' }).click()
  await page.getByLabel('Reason / feedback to contributor').fill('Synthetic identifiers removed.')
  await page.getByRole('checkbox', { name: /I reviewed/ }).check()
  await page.getByRole('button', { name: 'Preview publication' }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  for (let i = 0; i < 5; i++) {
    await page.keyboard.press('Tab')
    expect(await dialog.evaluate(el => el.contains(document.activeElement))).toBe(true)
  }
  await expect(page.getByRole('button', { name: 'Publish reviewed copy' })).toBeInViewport()
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()).violations).toEqual([])
  await page.screenshot({ path: 'test-results/mobile-publication-dialog.png' })
})

